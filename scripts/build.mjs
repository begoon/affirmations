import { readFile, writeFile } from 'node:fs/promises';
process.loadEnvFile('.env');
const languages = JSON.parse(await readFile('lang.json', 'utf8'));
const common = (await readFile('data/common.txt', 'utf8')).split(/\r?\n/).map(x => x.trim()).filter(Boolean);
if (!common.length || common.some(x => x.length > 4000)) throw Error('Invalid common seed');
const seeds = { common };
const operatorId = Number(process.env.OPERATOR_ID);
if (!Number.isSafeInteger(operatorId) || !operatorId) throw Error('Set OPERATOR_ID in .env');
await writeFile('tgcloud/lib/content.js', `// Generated by scripts/build.mjs; edit lang.json and data/ instead.\nexport const languages = ${JSON.stringify(languages)};\nexport const seeds = ${JSON.stringify(seeds)};\nexport const operatorId = ${operatorId};\n`);
console.log(`Built Russian UI and common seed (${common.length} texts).`);
